import { expect, test } from '@playwright/test'
import { mockRecordings } from './recordingsFixture'

test('one row per file, retry confirmation/cancellation, and failed retry preserves the good transcript', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const mock = await mockRecordings(page)
  await page.goto('/')
  const list = page.getByRole('list', { name: 'Recording files', exact: true })
  await expect(list.getByRole('listitem')).toHaveCount(3)
  await expect(page.getByRole('tablist', { name: 'Recordings', exact: true })).toHaveCount(0)
  await expect(page.getByText('Synthetic transcript.', { exact: true })).toBeVisible()
  const retry = page.getByRole('button', { name: 'Retranscribe alpha.wav', exact: true })
  await retry.click()
  const modal = page.getByRole('dialog', { name: 'Retranscribe recording?', exact: true })
  await expect(modal).toBeVisible()
  expect(mock.requests.retries).toEqual([])
  await modal.getByText('Cancel', { exact: true }).click()
  await expect(modal).toBeHidden()
  await retry.click()
  await modal.getByRole('button', { name: 'Retranscribe', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Cancel transcription of alpha.wav', exact: true })).toBeVisible()
  await expect(list.getByRole('listitem')).toHaveCount(3)
  expect(mock.requests.retries).toEqual(['good'])
  await expect(page.getByRole('button', { name: 'Retranscribe beta.wav', exact: true })).toBeDisabled()
  mock.finish('failed')
  await expect(page.getByText('Synthetic transcript.', { exact: true })).toBeVisible()
  await expect(list.getByRole('listitem').filter({ hasText: 'alpha.wav' }).getByText('Previous successful transcript available', { exact: true })).toBeVisible()
  await expect(list.getByRole('listitem')).toHaveCount(3)
  await expect(list.getByRole('listitem').filter({ hasText: 'alpha.wav' }).getByRole('img', { name: 'Failed', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Synthetic transcript.', { exact: true })).toBeVisible()
  await expect(list.getByRole('listitem')).toHaveCount(3)
  expect(mock.requests.unexpected).toEqual([])
  expect(errors).toEqual([])
})

test('first-time row starts immediately; failed attempts require confirmation and can be cancelled', async ({ page }) => {
  const mock = await mockRecordings(page)
  await page.goto('/')
  await page.getByRole('button', { name: 'Transcribe new.wav', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(mock.requests.starts).toEqual(['new.wav'])
  await page.getByRole('button', { name: 'Cancel transcription of new.wav', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Retranscribe new.wav', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Retranscribe beta.wav', exact: true }).click()
  const modal = page.getByRole('dialog', { name: 'Retranscribe recording?', exact: true })
  await expect(modal).toBeVisible()
  await modal.getByRole('button', { name: 'Retranscribe', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Cancel transcription of beta.wav', exact: true })).toBeVisible()
  expect(mock.requests.retries).toEqual(['failed'])
  expect(mock.requests.unexpected).toEqual([])
})

test('unavailable originals disable retry but keep the successful transcript selectable', async ({ page }) => {
  const mock = await mockRecordings(page)
  mock.files.splice(0, 1)
  mock.state.jobs[0] = { ...mock.state.jobs[0]!, retryAvailable: false, retryUnavailableReason: 'The original recording is unavailable.' }
  await page.goto('/')
  const retry = page.getByRole('button', { name: 'Retranscribe alpha.wav', exact: true })
  await expect(retry).toBeDisabled()
  await expect(page.getByText('Synthetic transcript.', { exact: true })).toBeVisible()
  const row = page.getByRole('listitem').filter({ hasText: 'alpha.wav' })
  await expect(row.getByText('Viewing transcript', { exact: true })).toBeVisible()
  expect(await row.evaluate(element => getComputedStyle(element).borderLeftWidth)).toBe('0px')
  expect(await row.evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgba(0, 0, 0, 0)')
  expect(mock.requests.retries).toEqual([])
})

test('duplicate uploaded content requests confirmation instead of starting another attempt', async ({ page }) => {
  const mock = await mockRecordings(page)
  await page.goto('/')
  await page.getByLabel('Choose audio file', { exact: true }).setInputFiles({ name: 'alpha.wav', mimeType: 'audio/wav', buffer: Buffer.from('synthetic') })
  await page.getByRole('button', { name: 'Transcribe', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Retranscribe recording?', exact: true })).toBeVisible()
  expect(mock.requests.retries).toEqual([])
  expect(mock.requests.starts).toEqual([])
  await page.getByRole('dialog').getByText('Cancel', { exact: true }).click()
  await expect(page.getByRole('list', { name: 'Recording files', exact: true }).getByRole('listitem')).toHaveCount(3)
  expect(mock.requests.unexpected).toEqual([])
})
