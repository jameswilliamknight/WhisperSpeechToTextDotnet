import { expect, test } from '@playwright/test'
import { mockRecordings } from './recordingsFixture'

test('persistent reconnects use a quiet centred nav status, transient reconnects stay silent', async ({ page }) => {
  await page.clock.install()
  const mock = await mockRecordings(page)
  await page.goto('/')
  await expect(page.getByText('Synthetic transcript.', { exact: true })).toBeVisible()
  const status = page.getByTestId('connection-status')
  const disconnect = () => page.evaluate(() => window.dispatchEvent(new Event('synthetic-watch-disconnect')))
  const reconnect = () => page.evaluate(() => window.dispatchEvent(new Event('synthetic-watch-reconnect')))
  await disconnect()
  await page.clock.runFor(1000)
  await expect(status).toBeEmpty()
  await reconnect()
  await page.clock.runFor(2000)
  await expect(status).toBeEmpty()
  await disconnect()
  await page.clock.runFor(1600)
  await expect(status).toHaveText('Reconnecting to recording updates…')
  await expect(page.getByRole('list', { name: 'Recording files', exact: true }).getByRole('listitem')).toHaveCount(3)
  await expect(page.getByRole('alert')).toHaveCount(0)
  const box = (await status.boundingBox())!, header = (await page.locator('header').first().boundingBox())!
  expect(box.x + box.width / 2).toBeCloseTo(header.x + header.width / 2, 0)
  expect(box.y).toBeGreaterThan(header.y)
  expect(box.y + box.height).toBeLessThan(header.y + header.height)
  await reconnect()
  await expect(status).toBeEmpty()
  await disconnect()
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await page.clock.runFor(2000)
  await expect(status).toBeEmpty()
  expect(mock.requests.unexpected).toEqual([])
})
