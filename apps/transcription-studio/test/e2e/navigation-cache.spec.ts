import { expect, test } from '@playwright/test'
import { mockReview } from './timelineFixture'

test('all screens warm once and navigation retains media, settings edits and rendered transcripts', async ({ page }) => {
  const requests: string[] = [], errors: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) requests.push(new URL(request.url()).pathname) })
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const unexpected = await mockReview(page, 'workspace')
  await expect.poll(() => requests.filter(path => path === '/api/studio').length).toBe(1)
  await expect.poll(() => requests.filter(path => path.endsWith('/audio')).length).toBe(2)
  const originalAudio = await page.locator('audio').elementHandle()
  const originalTranscript = await page.getByLabel('Transcript passages', { exact: true }).elementHandle()
  const benchmarkLoads = requests.filter(path => path === '/api/studio').length
  const audioLoads = requests.filter(path => path.endsWith('/audio')).length
  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  await page.getByRole('button', { name: 'Expand timeline to time scale', exact: true }).click()
  await nav.getByRole('link', { name: 'Settings', exact: true }).click()
  await page.getByLabel('Working directory', { exact: true }).fill('/synthetic/unsaved-navigation')
  await page.getByRole('tab', { name: 'Transcript', exact: true }).click()
  const timings: number[] = []
  for (let index = 0; index < 4; index++) {
    const started = Date.now()
    await nav.getByRole('link', { name: 'Benchmarks', exact: true }).click()
    await expect(page.getByLabel('Transcript segments', { exact: true })).toBeVisible()
    await nav.getByRole('link', { name: 'Transcribe', exact: true }).click()
    await expect(page.getByLabel('Transcript passages', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Fit timeline to width', exact: true })).toHaveAttribute('aria-pressed', 'true')
    timings.push(Date.now() - started)
    expect(await originalAudio!.evaluate(element => element === document.querySelector('audio'))).toBe(true)
    expect(await originalTranscript!.evaluate(element => element.isConnected)).toBe(true)
  }
  await nav.getByRole('link', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('tab', { name: 'Transcript', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: 'Folders', exact: true }).click()
  await expect(page.getByLabel('Working directory', { exact: true })).toHaveValue('/synthetic/unsaved-navigation')
  expect(requests.filter(path => path.endsWith('/audio')).length).toBe(audioLoads)
  expect(requests.filter(path => path === '/api/studio').length).toBe(benchmarkLoads)
  expect(Math.max(...timings)).toBeLessThan(1000)
  expect(unexpected).toEqual([])
  expect(errors).toEqual([])
})

test('inactive cached audio and Space shortcut stay suspended until returning to their screen', async ({ page }) => {
  const unexpected = await mockReview(page, 'workspace')
  const original = await page.locator('audio').elementHandle()
  await page.getByRole('button', { name: 'Play audio', exact: true }).click()
  await expect.poll(() => original!.evaluate(element => (element as HTMLAudioElement).currentTime)).toBeGreaterThan(0.2)
  await page.getByRole('link', { name: 'Benchmarks', exact: true }).click()
  await expect(page.getByLabel('Transcript segments', { exact: true })).toBeVisible()
  expect(await original!.evaluate(element => (element as HTMLAudioElement).paused)).toBe(true)
  await page.keyboard.press('Space')
  expect(await original!.evaluate(element => (element as HTMLAudioElement).paused)).toBe(true)
  await page.getByRole('button', { name: 'Play audio', exact: true }).click()
  const benchmark = await page.locator('audio').elementHandle()
  await page.getByRole('link', { name: 'Transcribe', exact: true }).click()
  await expect(page.getByLabel('Transcript passages', { exact: true })).toBeVisible()
  expect(await benchmark!.evaluate(element => (element as HTMLAudioElement).paused)).toBe(true)
  await expect(page.getByRole('button', { name: 'Pause audio', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Pause audio', exact: true }).click()
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Save settings', exact: true }).waitFor()
  await page.keyboard.press('Space')
  expect(await original!.evaluate(element => (element as HTMLAudioElement).paused)).toBe(true)
  expect(await benchmark!.evaluate(element => (element as HTMLAudioElement).paused)).toBe(true)
  await page.getByRole('link', { name: 'Transcribe', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Play audio', exact: true })).toBeVisible()
  await expect(page.getByText('Loading local workspace…', { exact: true })).toHaveCount(0)
  expect(unexpected).toEqual([])
})
